// 3. QUIZ DATA VALIDATION
// ============================================================================

// ตรวจสอบข้อมูลคำถามหลังจากลงทะเบียน
// เพื่อช่วยตรวจสอบว่าคำถามทั้ง 5 ข้อถูกโหลดครบ

(function validateUranusQuiz() {

  const questions = window.PLANET_QUIZ['uranus'];

  // --------------------------------------------------------------------------
  // CHECK QUESTIONS ARRAY
  // --------------------------------------------------------------------------

  if (!Array.isArray(questions)) {

    console.error(
      '[URANUS QUIZ] ไม่พบข้อมูลคำถามดาวยูเรนัส'
    );

    return;

  }

  // --------------------------------------------------------------------------
  // SHOW TOTAL QUESTIONS
  // --------------------------------------------------------------------------

  console.log(
    '[URANUS QUIZ] โหลดคำถามสำเร็จ:',
    questions.length,
    'ข้อ'
  );

  // --------------------------------------------------------------------------
  // VALIDATE EACH QUESTION
  // --------------------------------------------------------------------------

  questions.forEach(function (question, index) {

    const questionNumber = index + 1;

    // ตรวจสอบข้อความคำถาม
    if (
      typeof question.q !== 'string' ||
      question.q.trim() === ''
    ) {

      console.error(
        '[URANUS QUIZ] คำถามข้อที่ ' +
        questionNumber +
        ' ไม่มีข้อความคำถาม'
      );

    }

    // ตรวจสอบจำนวนตัวเลือก
    if (
      !Array.isArray(question.options) ||
      question.options.length !== 4
    ) {

      console.error(
        '[URANUS QUIZ] คำถามข้อที่ ' +
        questionNumber +
        ' ต้องมีตัวเลือก 4 ข้อ'
      );

    }

    // ตรวจสอบตำแหน่งคำตอบที่ถูกต้อง
    if (
      !Number.isInteger(question.correct) ||
      question.correct < 0 ||
      question.correct > 3
    ) {

      console.error(
        '[URANUS QUIZ] คำถามข้อที่ ' +
        questionNumber +
        ' มีตำแหน่งคำตอบไม่ถูกต้อง'
      );

    }

    // ตรวจสอบคำอธิบายเฉลย
    if (
      typeof question.explanation !== 'string'
    ) {

      console.error(
        '[URANUS QUIZ] คำถามข้อที่ ' +
        questionNumber +
        ' ไม่มีคำอธิบายเฉลย'
      );

    }

  });

  // --------------------------------------------------------------------------
  // CHECK TOTAL QUESTIONS
  // --------------------------------------------------------------------------

  if (questions.length === 5) {

    console.log(
      '[URANUS QUIZ] พร้อมใช้งานคำถามทั้งหมด 5 ข้อ'
    );

  } else {

    console.warn(
      '[URANUS QUIZ] จำนวนคำถามไม่เท่ากับ 5 ข้อ'
    );

  }

})();


